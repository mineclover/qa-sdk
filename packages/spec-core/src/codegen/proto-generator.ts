/**
 * IR → Protobuf (.proto) 코드 생성.
 *
 * IRModule을 소비하여 proto3 enum + message를 출력.
 */

import type { IRModule, IREnum, IRStruct } from "./ir.js";

function toUpperSnake(s: string): string {
  return s.toUpperCase().replace(/[^A-Z0-9]/g, "_");
}

function toPascal(s: string): string {
  return s.split(/[_-]/).map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
}

export interface ProtoOptions {
  /** protobuf package 이름 (기본: qa.spec.v1) */
  packageName?: string;
}

export function generateProtoFromIR(ir: IRModule, options: ProtoOptions = {}): string {
  const pkg = options.packageName ?? "qa.spec.v1";
  const lines: string[] = [];

  lines.push(`// Generated by @qa-sdk/spec-core`);
  lines.push(`// !! 자동 생성 파일 — 직접 수정 금지 !!`);
  lines.push(``);
  lines.push(`syntax = "proto3";`);
  lines.push(`package ${pkg};`);
  lines.push(``);

  // enums
  for (const en of ir.enums) {
    lines.push(irEnumToProto(en));
    lines.push(``);
  }

  // structs → messages
  if (ir.structs.length > 0) {
    lines.push(`// ── Export Surface Messages ──────────────────────`);
    lines.push(``);
    for (const st of ir.structs) {
      lines.push(irStructToProto(st));
      lines.push(``);
    }
  }

  return lines.join("\n");
}

function irEnumToProto(en: IREnum): string {
  const enumName = toPascal(en.id);
  const prefix = toUpperSnake(en.id);
  const lines: string[] = [];

  lines.push(`// ${en.id}${en.capacity ? ` (capacity: ${en.capacity})` : ""}`);
  lines.push(`enum ${enumName} {`);
  lines.push(`  ${prefix}_UNSPECIFIED = 0;`);

  for (const v of en.values) {
    lines.push(`  ${prefix}_${toUpperSnake(v.name)} = ${v.index + 1};`);
  }

  lines.push(`}`);
  return lines.join("\n");
}

function irStructToProto(st: IRStruct): string {
  const msgName = toPascal(st.id) + "Export";
  const lines: string[] = [];

  if (st.description) lines.push(`// ${st.description}`);
  lines.push(`message ${msgName} {`);

  let fieldNum = 1;
  for (const field of st.fields) {
    if (field.enumRef) {
      lines.push(`  ${toPascal(field.enumRef)} ${field.name} = ${fieldNum};`);
    } else {
      lines.push(`  string ${field.name} = ${fieldNum};`);
    }
    fieldNum++;
  }

  lines.push(`}`);
  return lines.join("\n");
}
