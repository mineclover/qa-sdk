/**
 * IR → TypeScript Declaration (.d.ts) 코드 생성.
 *
 * IRModule을 소비하여 순수 타입 선언(type + interface)을 출력.
 * const/런타임 값 없이 타입만 생성한다.
 */

import type { IRModule, IREnum, IRStruct } from "./ir.js";

export interface DtsOptions {
  header?: string;
}

// ── Naming ──────────────────────────────────────────

function toPascal(s: string): string {
  return s.split(/[_-]/).map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
}

// ── IR → .d.ts ──────────────────────────────────────

/**
 * IRModule → TypeScript Declaration (.d.ts) 파일 내용.
 */
export function generateDtsFromIR(ir: IRModule, options?: DtsOptions): string {
  const lines: string[] = [];

  lines.push(options?.header ?? "// Auto-generated by qa-sdk codegen. Do not edit.");
  lines.push("");

  // enums → Entry union types
  if (ir.enums.length > 0) {
    lines.push("// ── Entry Unions ──");
    for (const en of ir.enums) {
      lines.push(irEnumToDts(en));
    }
    lines.push("");
  }

  // structs → Coord interfaces + Version types
  if (ir.structs.length > 0) {
    lines.push("// ── Coord Interfaces ──");
    for (const st of ir.structs) {
      lines.push(irStructToDts(st, ir.enums));
    }
  }

  return lines.join("\n");
}

function irEnumToDts(en: IREnum): string {
  const typeName = toPascal(en.id) + "Entry";

  if (en.values.length === 0) {
    return `export type ${typeName} = string;`;
  }

  const literals = en.values.map(v => `"${v.name}"`).join(" | ");
  return `export type ${typeName} = ${literals};`;
}

function irStructToDts(st: IRStruct, enums: readonly IREnum[]): string {
  const pascal = toPascal(st.id);
  const lines: string[] = [];

  lines.push(`export interface ${pascal}Coord {`);

  for (const field of st.fields) {
    if (field.enumRef) {
      const matchedEnum = enums.find(e => e.id === field.enumRef);
      const fieldType = matchedEnum ? toPascal(matchedEnum.id) + "Entry" : "string";
      lines.push(`  readonly ${field.name}: ${fieldType};`);
    } else {
      lines.push(`  readonly ${field.name}: string;`);
    }
  }

  lines.push(`}`);

  // versions type (only if versions exist)
  if (st.versions && st.versions.length > 0) {
    const literals = st.versions.map(v => `"${v}"`).join(" | ");
    lines.push(`export type ${pascal}Version = ${literals};`);
  }

  return lines.join("\n");
}
