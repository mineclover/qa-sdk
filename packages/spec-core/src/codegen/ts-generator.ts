/**
 * IR → TypeScript 코드 생성.
 *
 * IRModule을 소비하여 TypeScript const/type + interface를 출력.
 * 데이터 원천에 직접 의존하지 않음 — IR만 알면 됨.
 */

import type { IRModule, IREnum, IRStruct } from "./ir.js";
import type { PrefixSpec } from "../spec/prefix-spec.types.js";

/** 이전 호환을 위한 AxisInput (IR 빌더에서도 사용) */
export interface AxisInput {
  id: string;
  entries: readonly string[];
  capacity?: number;
}

export interface GenerateOptions {
  axes: readonly AxisInput[];
  prefixSpecs: readonly PrefixSpec[];
  header?: string;
}

// ── Naming ──────────────────────────────────────────

function toPascal(s: string): string {
  return s.split(/[_-]/).map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
}

function toConstKey(entry: string): string {
  return entry.toUpperCase().replace(/[^A-Z0-9]/g, "_");
}

// ── IR → TypeScript ─────────────────────────────────

/**
 * IRModule → TypeScript 파일 내용.
 */
export function generateFromIR(ir: IRModule, header?: string): string {
  const lines: string[] = [];

  lines.push(header ?? `// Generated by @qa-sdk/spec-core`);
  lines.push("// !! 자동 생성 파일 — 직접 수정 금지 !!");
  lines.push("");

  for (const en of ir.enums) {
    lines.push(irEnumToTs(en));
    lines.push("");
  }

  if (ir.structs.length > 0) {
    lines.push("// ── Export Surface Interfaces ────────────────────");
    lines.push("");
    for (const st of ir.structs) {
      lines.push(irStructToTs(st));
      lines.push("");
    }
  }

  return lines.join("\n");
}

function irEnumToTs(en: IREnum): string {
  const constName = en.id.toUpperCase();
  const typeName = toPascal(en.id);
  const lines: string[] = [];

  lines.push(`/** ${en.id} axis entries${en.capacity ? ` (capacity: ${en.capacity})` : ""} */`);
  lines.push(`export const ${constName} = {`);
  for (const v of en.values) {
    lines.push(`  ${toConstKey(v.name)}: "${v.name}",`);
  }
  lines.push(`} as const;`);

  if (en.values.length > 0) {
    lines.push(`export type ${typeName} = typeof ${constName}[keyof typeof ${constName}];`);
  } else {
    lines.push(`export type ${typeName} = string;`);
  }

  return lines.join("\n");
}

function irStructToTs(st: IRStruct): string {
  const typeName = toPascal(st.id) + "Export";
  const lines: string[] = [];

  lines.push(`/** ${st.id} export surface${st.description ? ` — ${st.description}` : ""} */`);
  lines.push(`export interface ${typeName} {`);

  for (const field of st.fields) {
    if (field.enumRef) {
      lines.push(`  ${field.name}: ${toPascal(field.enumRef)};`);
    } else {
      lines.push(`  ${field.name}: string;`);
    }
  }

  lines.push(`}`);
  return lines.join("\n");
}

// ── Legacy API (이전 호환) ──────────────────────────

export function generateAxisType(axis: AxisInput): string {
  return irEnumToTs({
    id: axis.id,
    capacity: axis.capacity,
    values: axis.entries.map((name, index) => ({ name, index })),
  });
}

export function generateExportInterface(
  spec: PrefixSpec,
  _axisIdByDim: Map<string, string>,
): string {
  const fields = spec.export.dims.map(dim => {
    const dimRef = spec.dims[dim];
    return {
      name: dim,
      enumRef: dimRef?.kind === "axis" ? dimRef.axisId : null,
      dimKind: (dimRef?.kind ?? "axis") as "axis" | "prefix_ref" | "table_ref",
    };
  });
  return irStructToTs({ id: spec.id, description: `pattern: ${spec.export.pattern}`, fields });
}

export function generateTypescriptFile(options: GenerateOptions): string {
  const lines: string[] = [];
  lines.push(options.header ?? "// Generated by @qa-sdk/spec-core");
  lines.push("// !! 자동 생성 파일 — 직접 수정 금지 !!");
  lines.push("");

  for (const axis of options.axes) {
    lines.push(generateAxisType(axis));
    lines.push("");
  }

  if (options.prefixSpecs.length > 0) {
    lines.push("// ── Export Surface Interfaces ────────────────────");
    lines.push("");
    for (const spec of options.prefixSpecs) {
      const axisIdByDim = new Map<string, string>();
      for (const [label, dimRef] of Object.entries(spec.dims)) {
        if (dimRef.kind === "axis") axisIdByDim.set(label, dimRef.axisId);
      }
      lines.push(generateExportInterface(spec, axisIdByDim));
      lines.push("");
    }
  }

  return lines.join("\n");
}
