/**
 * IR → JavaScript 코드 생성.
 *
 * ESM (.mjs) + CommonJS (.cjs) 두 형식 지원.
 * IRModule을 소비하여 const 객체 + JSDoc 타입 힌트를 출력.
 */

import type { IRModule, IREnum, IRStruct } from "./ir.js";

export type JSFormat = "esm" | "cjs";

function toConstKey(entry: string): string {
  return entry.toUpperCase().replace(/[^A-Z0-9]/g, "_");
}

function toPascal(s: string): string {
  return s.split(/[_-]/).map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
}

// ── IR → JavaScript ─────────────────────────────────

export function generateJSFromIR(ir: IRModule, format: JSFormat, header?: string): string {
  const lines: string[] = [];

  lines.push(header ?? "// Generated by @qa-sdk/spec-core");
  lines.push("// !! 자동 생성 파일 — 직접 수정 금지 !!");
  lines.push("");

  for (const en of ir.enums) {
    lines.push(irEnumToJS(en, format));
    lines.push("");
  }

  if (ir.structs.length > 0) {
    lines.push("// ── Export Surface ───────────────────────────────");
    lines.push("");
    for (const st of ir.structs) {
      lines.push(irStructToJS(st, ir.enums, format));
      lines.push("");
    }
  }

  return lines.join("\n");
}

function irEnumToJS(en: IREnum, format: JSFormat): string {
  const constName = en.id.toUpperCase();
  const lines: string[] = [];

  lines.push(`/** @enum {string} ${en.id} axis entries${en.capacity ? ` (capacity: ${en.capacity})` : ""} */`);

  if (format === "esm") {
    lines.push(`export const ${constName} = Object.freeze({`);
  } else {
    lines.push(`const ${constName} = Object.freeze({`);
  }

  for (const v of en.values) {
    lines.push(`  ${toConstKey(v.name)}: "${v.name}",`);
  }
  lines.push(`});`);

  // 값 목록 배열 (런타임 검증용)
  const valuesName = `${constName}_VALUES`;
  const valuesStr = en.values.map(v => `"${v.name}"`).join(", ");

  if (format === "esm") {
    lines.push(`export const ${valuesName} = [${valuesStr}];`);
  } else {
    lines.push(`const ${valuesName} = [${valuesStr}];`);
  }

  return lines.join("\n");
}

function irStructToJS(st: IRStruct, enums: readonly IREnum[], format: JSFormat): string {
  const factoryName = `create${toPascal(st.id)}Export`;
  const lines: string[] = [];

  // JSDoc typedef
  const typeName = `${toPascal(st.id)}Export`;
  lines.push(`/**`);
  lines.push(` * @typedef {Object} ${typeName}`);
  for (const field of st.fields) {
    const jsType = field.enumRef ? "string" : "string";
    lines.push(` * @property {${jsType}} ${field.name}`);
  }
  lines.push(` */`);

  // 팩토리 + 런타임 검증
  lines.push(`/** ${st.description ?? st.id} */`);

  if (format === "esm") {
    lines.push(`export function ${factoryName}(dims) {`);
  } else {
    lines.push(`function ${factoryName}(dims) {`);
  }

  for (const field of st.fields) {
    if (field.enumRef) {
      const valuesName = `${field.enumRef.toUpperCase()}_VALUES`;
      const enumExists = enums.some(e => e.id === field.enumRef);
      if (enumExists) {
        lines.push(`  if (dims.${field.name} !== undefined && !${valuesName}.includes(dims.${field.name})) {`);
        lines.push(`    throw new Error(\`Invalid ${field.name}: "\${dims.${field.name}}". Expected one of: \${${valuesName}.join(", ")}\`);`);
        lines.push(`  }`);
      }
    }
  }

  lines.push(`  return dims;`);
  lines.push(`}`);

  return lines.join("\n");
}

// ── CommonJS exports 블록 ───────────────────────────

export function appendCJSExports(ir: IRModule, code: string): string {
  const exports: string[] = [];

  for (const en of ir.enums) {
    const constName = en.id.toUpperCase();
    exports.push(`  ${constName},`);
    exports.push(`  ${constName}_VALUES,`);
  }

  for (const st of ir.structs) {
    exports.push(`  create${toPascal(st.id)}Export,`);
  }

  return code + `\nmodule.exports = {\n${exports.join("\n")}\n};\n`;
}

/**
 * CJS 형식으로 전체 파일 생성.
 */
export function generateCJSFromIR(ir: IRModule, header?: string): string {
  const code = generateJSFromIR(ir, "cjs", header);
  return appendCJSExports(ir, code);
}
