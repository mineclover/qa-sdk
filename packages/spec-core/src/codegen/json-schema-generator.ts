/**
 * IR → JSON Schema 생성.
 *
 * IRModule을 소비하여 JSON Schema draft-2020-12를 출력.
 * axis enum → { "enum": [...] }, struct → { "properties": { ... } }
 */

import type { IRModule, IREnum, IRStruct } from "./ir.js";

function toPascal(s: string): string {
  return s.split(/[_-]/).map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
}

export function generateJsonSchemaFromIR(ir: IRModule): string {
  const schema: Record<string, unknown> = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: ir.name ?? "spec-core generated schema",
    description: "Generated by @qa-sdk/spec-core — 직접 수정 금지",
    $defs: {} as Record<string, unknown>,
  };

  const defs = schema.$defs as Record<string, unknown>;

  // enums → $defs
  for (const en of ir.enums) {
    defs[toPascal(en.id)] = irEnumToJsonSchema(en);
  }

  // structs → $defs
  for (const st of ir.structs) {
    defs[toPascal(st.id) + "Export"] = irStructToJsonSchema(st);
  }

  return JSON.stringify(schema, null, 2);
}

function irEnumToJsonSchema(en: IREnum): Record<string, unknown> {
  const values = en.values.map(v => v.name);
  const result: Record<string, unknown> = {
    type: "string",
    enum: values,
  };
  if (en.capacity !== undefined) {
    result.description = `${en.id} axis (capacity: ${en.capacity})`;
  }
  return result;
}

function irStructToJsonSchema(st: IRStruct): Record<string, unknown> {
  const properties: Record<string, unknown> = {};
  const required: string[] = [];

  for (const field of st.fields) {
    if (field.enumRef) {
      properties[field.name] = { $ref: `#/$defs/${toPascal(field.enumRef)}` };
    } else {
      properties[field.name] = { type: "string" };
    }
    required.push(field.name);
  }

  return {
    type: "object",
    description: st.description,
    properties,
    required,
    additionalProperties: false,
  };
}
