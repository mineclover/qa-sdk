/**
 * codegen.ts — MetaRegistryInput에서 TypeScript 타입 코드를 생성
 *
 * 스키마 정의를 기반으로:
 * 1. Leaf dim별 entry union 타입 생성
 * 2. Composite index별 encode/decode Record 타입 생성
 * 3. 스키마 검증(lint) 및 diff 리포트
 */

import type { MetaRegistryInput, DimInput } from './types.js';
import type { SchemaDiff } from './compile-schema.js';

// ── codegen ─────────────────────────────────────────────────────────────────

/**
 * MetaRegistryInput → TypeScript 타입 선언 문자열
 *
 * @param input   스키마 정의
 * @param options 생성 옵션
 * @returns       .ts 파일 내용
 *
 * @example
 * const code = generateTypes(RBAC_SCHEMA, { namespace: "RBAC" });
 * // export type RBACRoleEntry = "admin" | "editor" | "viewer";
 * // export interface RBACPermCoord { role: RBACRoleEntry; action: RBACActionEntry; ... }
 */
export function generateTypes(input: MetaRegistryInput, options?: GenerateTypesOptions): string {
  const prefix = options?.namespace ?? '';
  const exportKw = options?.exportAll === false ? '' : 'export ';
  const lines: string[] = [];

  lines.push('// Auto-generated by index-meta codegen. Do not edit.');
  lines.push('');

  // 1. Leaf dim별 entry union 타입
  for (const [dimId, dimDef] of Object.entries(input.dims)) {
    if (dimDef.kind.type === 'index_ref') continue;

    const typeName = `${prefix}${pascal(dimId)}Entry`;
    const snapshotEntries = collectAllEntries(dimDef);

    if (dimDef.kind.type === 'string_enum') {
      const union = snapshotEntries.map((e) => `"${e}"`).join(' | ');
      lines.push(`${exportKw}type ${typeName} = ${union || 'never'};`);
    } else {
      // number_enum
      const union = snapshotEntries.map((e) => String(e)).join(' | ');
      lines.push(`${exportKw}type ${typeName} = ${union || 'never'};`);
    }
  }

  lines.push('');

  // 2. Composite index별 coord interface
  for (const [indexId, indexDef] of Object.entries(input.indices)) {
    const interfaceName = `${prefix}${pascal(indexId)}Coord`;
    lines.push(`${exportKw}interface ${interfaceName} {`);

    for (const dimId of indexDef.dims) {
      const dimDef = input.dims[dimId];
      if (!dimDef) continue;

      let fieldType: string;
      if (dimDef.kind.type === 'string_enum') {
        fieldType = `${prefix}${pascal(dimId)}Entry`;
      } else if (dimDef.kind.type === 'number_enum') {
        fieldType = `${prefix}${pascal(dimId)}Entry`;
      } else {
        fieldType = 'number'; // index_ref
      }
      lines.push(`  ${dimId}: ${fieldType};`);
    }

    lines.push('}');
    lines.push('');
  }

  // 3. Version ID union per index
  for (const [indexId, indexDef] of Object.entries(input.indices)) {
    const typeName = `${prefix}${pascal(indexId)}Version`;
    const versionIds = Object.keys(indexDef.versions);
    const union = versionIds.map((v) => `"${v}"`).join(' | ');
    lines.push(`${exportKw}type ${typeName} = ${union || 'never'};`);
  }

  return lines.join('\n') + '\n';
}

export interface GenerateTypesOptions {
  /** 타입 이름 접두사. 예: "RBAC" → RBACRoleEntry */
  namespace?: string;
  /** false면 export 키워드 생략 (기본: true) */
  exportAll?: boolean;
}

// ── lint ─────────────────────────────────────────────────────────────────────

export interface LintDiagnostic {
  level: 'error' | 'warning' | 'info';
  dimId?: string;
  indexId?: string;
  versionId?: string;
  message: string;
}

/**
 * 스키마 정의의 잠재적 문제를 검출한다.
 *
 * - 비어있는 entries
 * - capacity headroom 과다 (>90% 미사용)
 * - 미참조 dim
 * - index_ref 참조 대상 존재 검증
 * - 중복 entry 값 검출
 */
export function lintSchema(input: MetaRegistryInput): LintDiagnostic[] {
  const diagnostics: LintDiagnostic[] = [];

  // dim별 검사
  const referencedDims = new Set<string>();
  for (const indexDef of Object.values(input.indices)) {
    for (const dimId of indexDef.dims) referencedDims.add(dimId);
  }

  for (const [dimId, dimDef] of Object.entries(input.dims)) {
    // 미참조 dim
    if (!referencedDims.has(dimId)) {
      diagnostics.push({
        level: 'warning',
        dimId,
        message: `dim "${dimId}" is not referenced by any index`,
      });
    }

    // index_ref 참조 대상 검증
    if (dimDef.kind.type === 'index_ref') {
      if (!input.indices[dimDef.kind.indexId]) {
        diagnostics.push({
          level: 'error',
          dimId,
          message: `index_ref target "${dimDef.kind.indexId}" not found in indices`,
        });
      }
    }

    // snapshot별 검사
    for (const [snapId, snap] of Object.entries(dimDef.snapshots)) {
      if (snap.entries.length === 0) {
        diagnostics.push({
          level: 'warning',
          dimId,
          versionId: snapId,
          message: `snapshot "${snapId}" has no entries`,
        });
      }

      // capacity headroom 과다
      const cap = snap.capacity ?? snap.entries.length;
      const usage = snap.entries.length / cap;
      if (cap > 1 && usage < 0.1) {
        diagnostics.push({
          level: 'info',
          dimId,
          versionId: snapId,
          message: `snapshot "${snapId}" has ${(usage * 100).toFixed(0)}% usage (${snap.entries.length}/${cap})`,
        });
      }

      // 중복 entry
      const seen = new Set<string>();
      for (const entry of snap.entries) {
        const key = String(entry);
        if (seen.has(key)) {
          diagnostics.push({
            level: 'error',
            dimId,
            versionId: snapId,
            message: `duplicate entry "${key}" in snapshot "${snapId}"`,
          });
        }
        seen.add(key);
      }
    }
  }

  // index별 검사
  for (const [indexId, indexDef] of Object.entries(input.indices)) {
    // 미존재 dim 참조
    for (const dimId of indexDef.dims) {
      if (!input.dims[dimId]) {
        diagnostics.push({
          level: 'error',
          indexId,
          message: `index "${indexId}" references unknown dim "${dimId}"`,
        });
      }
    }

    // version별 snapshot 참조 검증
    for (const [verId, verDef] of Object.entries(indexDef.versions)) {
      for (const dimId of indexDef.dims) {
        const snapId = verDef.snapshots[dimId];
        if (!snapId) {
          diagnostics.push({
            level: 'error',
            indexId,
            versionId: verId,
            message: `version "${verId}" missing snapshot for dim "${dimId}"`,
          });
          continue;
        }
        const dimDef = input.dims[dimId];
        if (dimDef && !dimDef.snapshots[snapId]) {
          diagnostics.push({
            level: 'error',
            indexId,
            versionId: verId,
            message: `version "${verId}" references unknown snapshot "${snapId}" for dim "${dimId}"`,
          });
        }
      }
    }
  }

  return diagnostics;
}

// ── diff report ─────────────────────────────────────────────────────────────

/**
 * SchemaDiff를 사람이 읽을 수 있는 문자열로 포맷.
 */
export function formatSchemaDiff(diff: SchemaDiff): string {
  const lines: string[] = [];

  if (diff.added.length > 0) {
    lines.push('Added tables:');
    for (const table of diff.added) {
      const versions = [...table.versions.keys()].join(', ');
      lines.push(`  + ${table.id} (${table.kind}) [${versions}]`);
    }
  }

  if (diff.removed.length > 0) {
    lines.push('Removed tables:');
    for (const id of diff.removed) {
      lines.push(`  - ${id}`);
    }
  }

  if (diff.changed.length > 0) {
    lines.push('Changed tables:');
    for (const change of diff.changed) {
      lines.push(`  ~ ${change.tableId}`);
      for (const v of change.addedVersions) {
        if (v.previousCapacity !== undefined) {
          lines.push(`    capacity ${v.versionId}: ${v.previousCapacity} → ${v.capacity}`);
        } else {
          lines.push(`    + version ${v.versionId} (capacity: ${v.capacity})`);
        }
      }
      for (const v of change.removedVersions) {
        lines.push(`    - version ${v}`);
      }
    }
  }

  if (lines.length === 0) {
    return 'No changes.';
  }

  return lines.join('\n');
}

// ── 내부 헬퍼 ───────────────────────────────────────────────────────────────

function pascal(str: string): string {
  return str
    .split(/[_\-\s]+/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

function collectAllEntries(dim: DimInput): string[] {
  const all = new Set<string>();
  for (const snap of Object.values(dim.snapshots)) {
    for (const entry of snap.entries) {
      all.add(String(entry));
    }
  }
  return [...all];
}
